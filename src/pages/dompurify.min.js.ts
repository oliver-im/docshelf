import { readFile } from 'node:fs/promises';
import type { APIRoute } from 'astro';

export const prerender = true;
const sanitizerBundle = readFile(new URL('./purify.min.js', import.meta.resolve('dompurify')));

export const GET: APIRoute = async () => new Response(await sanitizerBundle, {
  headers: { 'Content-Type': 'text/javascript; charset=utf-8' },
});
